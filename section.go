package main

import (
	"fmt"
	"strings"
)

const (
	openMarker  = "<!-- agents "
	closeMarker = "<!-- /agents -->"
)

type State int

const (
	Unset State = iota
	Rule
	Opposite
)

// Selection maps a group ID and part ID to the part's state.
type Selection map[string]map[string]State

func defaults(groups []Group) Selection {
	sel := Selection{}
	for _, g := range groups {
		sel[g.ID] = map[string]State{}
		for _, p := range g.Parts {
			switch p.Default {
			case "rule":
				sel[g.ID][p.ID] = Rule
			case "opposite":
				sel[g.ID][p.ID] = Opposite
			}
		}
	}
	return sel
}

// set changes a part's state. Choosing a part of a group that picks one
// unsets the others.
func (s Selection) set(g Group, part string, st State) {
	if g.One && st != Unset {
		clear(s[g.ID])
	}
	s[g.ID][part] = st
}

// encode writes the selection as marker fields, e.g. "code=tests,!comments".
// A "!" marks the opposite. Unset parts are left out.
func (s Selection) encode(groups []Group) string {
	var fields []string
	for _, g := range groups {
		var ids []string
		for _, p := range g.Parts {
			switch s[g.ID][p.ID] {
			case Rule:
				ids = append(ids, p.ID)
			case Opposite:
				ids = append(ids, "!"+p.ID)
			}
		}
		fields = append(fields, g.ID+"="+strings.Join(ids, ","))
	}
	return strings.Join(fields, " ")
}

// readSelection returns the selection recorded in doc. Groups it doesn't
// mention keep their defaults, and unknown parts are dropped.
func readSelection(doc string, groups []Group) (Selection, bool) {
	sel := defaults(groups)
	var marker string
	for line := range strings.Lines(doc) {
		if strings.HasPrefix(line, openMarker) {
			marker = strings.TrimSuffix(strings.TrimPrefix(strings.TrimSpace(line), openMarker), "-->")
			break
		}
	}
	if marker == "" {
		return sel, false
	}
	recorded := map[string]string{}
	for _, field := range strings.Fields(marker) {
		if k, v, ok := strings.Cut(field, "="); ok {
			recorded[k] = v
		}
	}
	for _, g := range groups {
		v, ok := recorded[g.ID]
		if !ok {
			continue
		}
		clear(sel[g.ID])
		for id := range strings.SplitSeq(v, ",") {
			st := Rule
			if rest, ok := strings.CutPrefix(id, "!"); ok && !g.One {
				id, st = rest, Opposite
			}
			if g.part(id) != nil {
				sel.set(g, id, st)
			}
		}
	}
	return sel, true
}

func (g Group) part(id string) *Part {
	for i := range g.Parts {
		if g.Parts[i].ID == id {
			return &g.Parts[i]
		}
	}
	return nil
}

func render(groups []Group, sel Selection) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s%s -->\nGenerated by agents. Run it again to change these rules.\n", openMarker, sel.encode(groups))
	for _, g := range groups {
		var lines []string
		title := g.Title
		for _, p := range g.Parts {
			switch st := sel[g.ID][p.ID]; {
			case g.One && st == Rule:
				title += ": " + p.ID
				lines = append(lines, p.Rule)
			case st == Rule:
				lines = append(lines, "- "+p.Rule)
			case st == Opposite:
				lines = append(lines, "- "+p.Opposite)
			}
		}
		if len(lines) > 0 {
			fmt.Fprintf(&b, "\n## %s\n\n%s\n", title, strings.Join(lines, "\n"))
		}
	}
	b.WriteString(closeMarker + "\n")
	return b.String()
}

// splice replaces the generated section of doc, or appends one.
func splice(doc, section string) string {
	start := -1
	if strings.HasPrefix(doc, openMarker) {
		start = 0
	} else if i := strings.Index(doc, "\n"+openMarker); i >= 0 {
		start = i + 1
	}
	if start < 0 {
		if doc != "" && !strings.HasSuffix(doc, "\n") {
			doc += "\n"
		}
		return doc + "\n" + section
	}
	end := strings.Index(doc[start:], closeMarker)
	if end < 0 {
		return doc[:start] + section
	}
	end += start + len(closeMarker)
	if end < len(doc) && doc[end] == '\n' {
		end++
	}
	return doc[:start] + section + doc[end:]
}
